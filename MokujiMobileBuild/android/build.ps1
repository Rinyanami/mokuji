[CmdletBinding()]
param(
    [Parameter(Mandatory=$true)][string]$Jdk,
    [Parameter(Mandatory=$true)][string]$BuildTools,
    [Parameter(Mandatory=$true)][string]$PlatformJar,
    [Parameter(Mandatory=$true)][string]$Keystore,
    [string]$EcjJar=$env:MOKUJI_ECJ_JAR,
    [string]$KeyAlias='mokuji-release',
    [string]$Output=(Join-Path $PSScriptRoot 'dist\Mokuji-Android.apk')
)
$ErrorActionPreference='Stop'
if (-not $env:MOKUJI_SIGN_PASS) { throw 'Set MOKUJI_SIGN_PASS in this process.' }
$java=Join-Path $Jdk 'bin\java.exe'
$javac=Join-Path $Jdk 'bin\javac.exe'
$jar=Join-Path $Jdk 'bin\jar.exe'
$aapt=Join-Path $BuildTools 'aapt2.exe'
$zipalign=Join-Path $BuildTools 'zipalign.exe'
$d8=Join-Path $BuildTools 'lib\d8.jar'
$apksigner=Join-Path $BuildTools 'lib\apksigner.jar'
$work=Join-Path ([IO.Path]::GetTempPath()) ('Mokuji-apk-'+[guid]::NewGuid().ToString('N'))
foreach ($folder in @($work, "$work\classes", "$work\dex", [IO.Path]::GetDirectoryName([IO.Path]::GetFullPath($Output)))) {
    $null=[IO.Directory]::CreateDirectory($folder)
}
function Run-Tool([string]$Tool, [string[]]$Arguments) {
    & $Tool @Arguments
    if ($LASTEXITCODE -ne 0) { throw "$Tool returned $LASTEXITCODE" }
}
try {
    $assetsDir = Join-Path $work 'assets\web'
    $null = [IO.Directory]::CreateDirectory($assetsDir)
    $webSource = Join-Path (Split-Path $PSScriptRoot -Parent) 'server\web'
    if (Test-Path $webSource) {
        Get-ChildItem $webSource | Where-Object { $_.Name -ne 'install' } | ForEach-Object {
            Copy-Item $_.FullName (Join-Path $assetsDir $_.Name) -Recurse -Force
        }
    }
    Run-Tool $aapt @('compile','--dir',"$PSScriptRoot\res",'-o',"$work\resources.zip")
    Run-Tool $aapt @('link','--manifest',"$PSScriptRoot\AndroidManifest.xml",'-A',"$work\assets",'-I',$PlatformJar,'-o',"$work\resources.apk","$work\resources.zip")
    $sources=@(Get-ChildItem -LiteralPath "$PSScriptRoot\src" -Filter '*.java' -File -Recurse | ForEach-Object FullName)
    if ($EcjJar) {
        Run-Tool $java (@('-jar',$EcjJar,'-source','8','-target','8','-nowarn','-proc:none','-encoding','UTF-8','-classpath',$PlatformJar,'-d',"$work\classes") + $sources)
    } else {
        Run-Tool $javac (@('-encoding','UTF-8','--release','8','--class-path',$PlatformJar,'-d',"$work\classes") + $sources)
    }
    Run-Tool $jar @('cf',"$work\bytecode.jar",'-C',"$work\classes",'.')
    Run-Tool $java @('-cp',$d8,'com.android.tools.r8.D8','--release','--min-api','26','--lib',$PlatformJar,'--output',"$work\dex","$work\bytecode.jar")
    Run-Tool $jar @('uf',"$work\resources.apk",'-C',"$work\dex",'classes.dex')
    Run-Tool $java @("$PSScriptRoot\NormalizeApk.java","$work\resources.apk","$work\normalized.apk")
    Run-Tool $zipalign @('-f','4',"$work\normalized.apk","$work\aligned.apk")
    Run-Tool $java @('-jar',$apksigner,'sign','--ks',$Keystore,'--ks-key-alias',$KeyAlias,'--ks-pass','env:MOKUJI_SIGN_PASS','--v1-signing-enabled','true','--v2-signing-enabled','true','--v3-signing-enabled','true','--v4-signing-enabled','false','--out',"$work\signed.apk","$work\aligned.apk")
    Run-Tool $java @('-jar',$apksigner,'verify','--verbose','--print-certs',"$work\signed.apk")
    Run-Tool $zipalign @('-c','4',"$work\signed.apk")
    Copy-Item -LiteralPath "$work\signed.apk" -Destination $Output -Force
    Get-FileHash -Algorithm SHA256 -LiteralPath $Output | Select-Object -ExpandProperty Hash
} finally {
    # The temporary directory contains only build intermediates generated by this invocation.
    $resolved=[IO.Path]::GetFullPath($work)
    if ([IO.Path]::GetDirectoryName($resolved) -eq [IO.Path]::GetTempPath().TrimEnd('\') -and [IO.Path]::GetFileName($resolved) -match '^Mokuji-apk-[a-f0-9]{32}$') {
        Remove-Item -LiteralPath $resolved -Recurse -Force
    }
}
