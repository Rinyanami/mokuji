function decode(text) {
	return text.replace(/&(#x[\da-f]+|#\d+|[a-z][a-z\d]*);/gi, (original, key) => {
		if (key[0] !== "#") return entities.get(key.toLowerCase()) ?? original;
		const hex = key[1].toLowerCase() === "x";
		const cp = Number.parseInt(key.slice(hex ? 2 : 1), hex ? 16 : 10);
		return cp > 0 && cp <= 1114111 && !(cp >= 55296 && cp <= 57343) ? String.fromCodePoint(cp) : "�";
	});
}
function clean(text, maxLength) {
	const value = decode(text || "").replace(/\s+/g, " ").trim();
	return value && value.length <= maxLength ? value : "";
}
function attributes(tag) {
	const attrs = Object.create(null);
	for (const match of tag.matchAll(/([^\s=/><]+)\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s"'=<>]+))/g)) attrs[match[1].toLowerCase()] = match[2] ?? match[3] ?? match[4];
	return attrs;
}
function extract(html, source) {
	const visible = html.replace(/<!--[\s\S]*?(?:-->|$)|<(script|style|noscript|template|textarea)\b[^>]*>[\s\S]*?(?:<\/\1\s*>|$)/gi, "");
	const tokens = /<\/?([a-z][\w:-]*)\b(?:[^>"']|"[^"]*"|'[^']*')*>|([^<]+)/gi;
	if (source.provider === "qidian") {
		const meta = new Map();
		for (const token of visible.matchAll(tokens)) {
			if (token[1]?.toLowerCase() !== "meta") continue;
			const attr = attributes(token[0]);
			const key = (attr.property || attr.name || "").toLowerCase();
			if (key.startsWith("og:")) meta.set(key, attr.content);
		}
		const pageUrl = meta.get("og:url") || meta.get("og:novel:read_url");
		if (pageUrl) {
			let resolved;
			try {
				resolved = new URL(decode(pageUrl), source.url).href;
			} catch {
				return null;
			}
			const work = parseOfficialLink(resolved);
			if (work?.provider !== source.provider || work.externalId !== source.externalId) return null;
		}
		const name = meta.get("og:novel:book_name");
		if (!name && meta.get("og:type") !== "novel") return null;
		const title = clean(name || meta.get("og:title"), 300);
		const author = clean(meta.get("og:novel:author"), 200);
		return title && author ? {
			title,
			author,
			url: source.url
		} : null;
	}
	let scope = "", capture = "", endTag = "";
	const fields = {
		title: "",
		author: ""
	};
	for (const token of visible.matchAll(tokens)) {
		if (token[2] !== void 0) {
			if (capture) fields[capture] += token[2];
			continue;
		}
		const tag = token[1].toLowerCase();
		if (token[0].startsWith("</")) {
			if (capture && tag === endTag) {
				capture = "";
				endTag = "";
			}
			if (scope && tag === scope) scope = "";
			if (!capture && fields.title && fields.author) break;
			continue;
		}
		if (![
			"div",
			"span",
			"h1"
		].includes(tag)) continue;
		const classes = (attributes(token[0]).class || "").split(/\s+/);
		if (classes.includes("info-name")) scope = tag;
		if (scope && tag === "h1") {
			capture = "title";
			endTag = tag;
		}
		if (classes.includes("author-name-text")) {
			capture = "author";
			endTag = tag;
		}
	}
	if (capture) return null;
	const title = clean(fields.title, 300);
	const author = clean(fields.author, 200);
	return title && author ? {
		title,
		author,
		url: source.url
	} : null;
}
async function readPrefix(body) {
	if (!body) return "";
	const reader = body.getReader();
	const decoder = new TextDecoder();
	let html = "", left = byteLimit;
	try {
		while (left > 0) {
			const { value, done } = await reader.read();
			if (done) break;
			const part = value.subarray(0, left);
			html += decoder.decode(part, { stream: true });
			left -= part.byteLength;
		}
		return html + decoder.decode();
	} finally {
		reader.cancel().catch(() => {});
		reader.releaseLock();
	}
}
async function lookup(source, fetchImpl, controller) {
	let url = source.provider === "qidian" ? "https://m.qidian.com/book/" + source.externalId + "/" : source.url;
	for (let redirects = 0; redirects <= 2; redirects++) {
		const reply = await fetchImpl(url, {
			redirect: "manual",
			signal: controller.signal,
			credentials: "omit",
			headers: {
				Accept: "text/html, application/xhtml+xml",
				"User-Agent": "MokujiCatalog/1.0"
			}
		});
		if ([
			301,
			302,
			303,
			307,
			308
		].includes(reply.status)) {
			reply.body?.cancel().catch(() => {});
			const location = reply.headers.get("location");
			if (!location || redirects === 2) return null;
			const next = new URL(location, url);
			const work = parseOfficialLink(next.href);
			if (next.protocol !== "https:" || work?.provider !== source.provider || work.externalId !== source.externalId) return null;
			next.search = "";
			next.hash = "";
			url = next.href;
			continue;
		}
		if (reply.status !== 200 || !/^(?:text\/html|application\/xhtml\+xml)(?:\s*;|$)/i.test(reply.headers.get("content-type") || "")) {
			reply.body?.cancel().catch(() => {});
			return null;
		}
		return extract(await readPrefix(reply.body), source);
	}
	return null;
}
async function lookupOfficial(source, fetchImpl = fetch) {
	if (!source || !["fanqie", "qidian"].includes(source.provider) || typeof source.externalId !== "string" || !idPattern.test(source.externalId)) return null;
	const safe = canonical(source.provider, source.externalId);
	const controller = new AbortController();
	let timer;
	try {
		const deadline = new Promise((resolve) => {
			timer = setTimeout(() => {
				controller.abort();
				resolve(null);
			}, timeout);
		});
		return await Promise.race([lookup(safe, fetchImpl, controller), deadline]);
	} catch {
		return null;
	} finally {
		clearTimeout(timer);
		controller.abort();
	}
}
