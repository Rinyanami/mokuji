function findShelfBook(state, books, work, requestedId) {
	const bgm = work.sources.find((source) => source.provider === "bangumi");
	const bgmId = bgm ? Number(bgm.externalId) : void 0;
	const sourceUrls = new Set(work.sources.map((source) => source.url));
	const linkedIds = new Set();
	const entries = new Map(state.entries.map((entry) => [entry.bookId, entry]));
	const matchesUrl = (url) => {
		if (!url) return false;
		return sourceUrls.has(url) || sourceUrls.has(parseOfficialLink(url)?.url ?? "");
	};
	const matchesEntry = (entry) => entry?.catalogWorkId === work.id || bgmId !== void 0 && entry?.bangumiId === bgmId;
	for (const book of books) {
		const entry = entries.get(book.id);
		if (matchesEntry(entry) || bgmId && book.id === "custom-bgm-" + bgmId || matchesUrl(entry?.sourceUrl) || matchesUrl(book.sourceUrl)) linkedIds.add(book.id);
	}
	for (const source of state.cotexSources ?? []) if (matchesUrl(source.sourceUrl)) linkedIds.add(source.bookId);
	if (linkedIds.size > 1 || requestedId && linkedIds.size && !linkedIds.has(requestedId)) return { error: "这些来源已关联到书架中的不同作品，请先核对原有记录。" };
	const fixed = requestedId || [...linkedIds][0];
	const compatible = (book) => {
		const entry = entries.get(book.id);
		if (entry?.catalogWorkId && entry.catalogWorkId !== work.id) return false;
		const priorBgm = entry?.bangumiId || Number(/^custom-bgm-(\d+)$/.exec(book.id)?.[1]);
		if (priorBgm && bgmId && priorBgm !== bgmId) return false;
		return [
			book.sourceUrl,
			entry?.sourceUrl,
			...(state.cotexSources ?? []).filter((source) => source.bookId === book.id).map((source) => source.sourceUrl)
		].every((url) => {
			const prior = url ? parseOfficialLink(url) : null;
			return !prior || !work.sources.some((source) => source.provider === prior.provider && source.externalId !== prior.externalId);
		});
	};
	if (fixed) {
		const book = books.find((book) => book.id === fixed);
		if (!book) return { error: "所选书架作品已经不存在，请刷新后重试。" };
		if (!compatible(book)) return { error: "该书架作品已关联另一条书目或版本。" };
		if (requestedId && !linkedIds.size && normalized(book.title) === normalized(work.title) && knownAuthor(book.author) && knownAuthor(work.author) && normalized(book.author) !== normalized(work.author)) return { error: "同名作品的作者不同，请选择对应作品。" };
		return { book };
	}
	if (!knownAuthor(work.author)) return {};
	const candidates = books.filter((book) => normalized(book.title) === normalized(work.title) && normalized(book.author) === normalized(work.author) && compatible(book));
	if (candidates.length > 1) return { error: "书架里有多个可能的版本，请选择要关联的作品。" };
	return { book: candidates[0] };
}
