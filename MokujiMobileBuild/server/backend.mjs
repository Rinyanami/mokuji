async function saveSharedWork(raw) {
	const input = saveInput.parse(raw);
	const sources = [];
	if (input.url) sources.push(sourceFromUrl(input.url));
	if (input.bangumiId) {
		const bgm = bangumiSource(input.bangumiId);
		const fromUrl = sources.find((s) => s.provider === "bangumi");
		if (fromUrl && fromUrl.externalId !== bgm.externalId) throw new AppError("链接与 Bangumi 条目 ID 不一致。");
		if (!fromUrl) sources.push(bgm);
	}
	const manual = {
		title: input.title || "",
		author: input.author || ""
	};
	const fetched = new Map();
	const db = getDb();
	for (let attempt = 0; attempt < 3; attempt++) {
		const owners = await Promise.all(sources.map(sourceOwner));
		const targets = new Set([...owners.filter((id) => id !== null), ...input.workId ? [input.workId] : []]);
		if (targets.size > 1) throw new AppError("来源已关联到其他作品，请核对作品及版本。", 409);
		const target = [...targets][0];
		let work = target ? await getSharedWork(target) : null;
		if (target && !work) throw new AppError("找不到要关联的共享作品。", 404);
		if (work && !compatible(work, sources)) throw new AppError("这部作品已有同平台的其他条目，请核对分册或版本。", 409);
		if (work && owners.every((id) => id === work.id)) return work;
		const verified = (await Promise.all(sources.filter((_, i) => !owners[i]).map(async (source) => {
			let value = fetched.get(source.url);
			if (!value) {
				value = await metadata(source);
				fetched.set(source.url, value);
			}
			if (source.provider !== "bangumi" && !value.title && (!manual.title || !manual.author)) throw new AppError("官方页面暂未提供书目，请手动补全书名和作者后保存。");
			return value;
		}))).filter((detail) => detail.title);
		for (const [i, detail] of verified.entries()) {
			checkMetadata(manual, detail);
			if (work) checkMetadata(work, detail);
			for (const other of verified.slice(i + 1)) checkMetadata(detail, other);
		}
		if (work && !verified.length) checkMetadata(work, manual);
		const title = verified[0]?.title || manual.title;
		const author = verified.find((detail) => detail.author)?.author || manual.author;
		let newId;
		const titleKey = normalized(title), byAuthor = knownAuthor(author);
		if (!work) {
			if (!titleKey) throw new AppError("请补全书名后保存。");
			if (!sources.length && !byAuthor) throw new AppError("手动新增作品时请填写书名和作者，或提供官方来源链接。");
			let hasOtherEditions = false;
			if (byAuthor) {
				const rows = await db.select().from(sharedWorks).where(and(eq(sharedWorks.titleKey, titleKey), eq(sharedWorks.authorKey, byAuthor))).limit(41).all();
				if (rows.length > 40) throw new AppError("有多部同名作品，请选择具体条目后再关联。", 409);
				const matches = (await withSources(rows)).filter((candidate) => compatible(candidate, sources));
				if (matches.length > 1) throw new AppError("有多部书名和作者相同的作品，请选择具体条目后再关联。", 409);
				work = matches[0] || null;
				hasOtherEditions = rows.length > 0;
			}
			if (!work) {
				const source = sources.find((s) => s.provider === "bangumi") || sources[0];
				newId = await stableId(byAuthor && !hasOtherEditions ? [
					"title-author",
					titleKey,
					byAuthor
				] : [
					"source",
					source.provider,
					source.externalId
				]);
			}
		}
		const id = work?.id || newId;
		if (work && !sources.length) return work;
		const inserts = sources.map((source) => db.insert(sharedSources).values({
			workId: id,
			...source
		}).onConflictDoUpdate({
			target: [sharedSources.provider, sharedSources.externalId],
			set: { workId: sql`CASE WHEN ${sharedSources.workId}=excluded.work_id THEN excluded.work_id ELSE NULL END` }
		}));
		try {
			await db.batch([db.insert(sharedWorks).values({
				id,
				title: work?.title || title,
				author: work?.author ?? author,
				titleKey: work ? normalized(work.title) : titleKey,
				authorKey: normalized(work?.author ?? author)
			}).onConflictDoNothing(), ...inserts]);
		} catch (error) {
			if (!isConstraint(error)) throw error;
			if (attempt < 2) continue;
			throw new AppError("来源关联已变化，请重新查看共享条目。", 409);
		}
		const saved = await getSharedWork(id);
		if (!saved) throw new AppError("共享作品暂时无法读取，请重试。", 503);
		return saved;
	}
	throw new AppError("共享条目正在更新，请重试。", 409);
}
