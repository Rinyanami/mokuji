var LocalD1Statement = class LocalD1Statement {
	constructor(database, sql, parameters = []) {
		this.database = database;
		this.sql = sql;
		this.parameters = parameters;
	}
	bind(...parameters) {
		return new LocalD1Statement(this.database, this.sql, parameters.map(parameter));
	}
	statement(arrays = false) {
		const statement = this.database.sqlite.prepare(this.sql);
		if (arrays) statement.setReturnArrays(true);
		return statement;
	}
	metadata(start, changes = 0, lastRowId = 0, rowsRead = 0) {
		return {
			duration: performance.now() - start,
			changes: numeric$1(changes),
			last_row_id: numeric$1(lastRowId),
			changed_db: Number(changes) > 0,
			rows_read: rowsRead,
			rows_written: numeric$1(changes),
			size_after: 0
		};
	}
	executeAll() {
		const start = performance.now();
		const results = this.statement().all(...this.parameters);
		const change = /^\s*(insert|update|delete|replace)/i.test(this.sql) ? this.database.sqlite.prepare("SELECT changes() AS changes, last_insert_rowid() AS id").get() : {
			changes: 0,
			id: 0
		};
		return {
			success: true,
			results,
			meta: this.metadata(start, change.changes, change.id, results.length)
		};
	}
	async all() {
		return this.executeAll();
	}
	async raw(options = {}) {
		const statement = this.statement(true);
		const rows = statement.all(...this.parameters);
		return options.columnNames ? [statement.columns().map((column) => column.name), ...rows] : rows;
	}
	async first(column) {
		const row = this.statement().get(...this.parameters);
		if (!row) return null;
		if (column === void 0) return row;
		if (!(column in row)) throw new Error(`D1_ERROR: Column not found: ${column}`);
		return row[column];
	}
	async run() {
		const start = performance.now();
		const result = this.statement().run(...this.parameters);
		return {
			success: true,
			results: [],
			meta: this.metadata(start, result.changes, result.lastInsertRowid)
		};
	}
};
var LocalD1Database = class {
	constructor(filename) {
		if (filename !== ":memory:") mkdirSync(dirname(filename), { recursive: true });
		this.sqlite = new DatabaseSync(filename);
		this.sqlite.exec("PRAGMA foreign_keys = ON; PRAGMA journal_mode = WAL;");
	}
	prepare(sql) {
		return new LocalD1Statement(this, sql);
	}
	async batch(statements) {
		this.sqlite.exec("BEGIN IMMEDIATE");
		try {
			const results = statements.map((statement) => {
				if (!(statement instanceof LocalD1Statement) || statement.database !== this) throw new TypeError("Statements must belong to this local D1 database.");
				return statement.executeAll();
			});
			this.sqlite.exec("COMMIT");
			return results;
		} catch (error) {
			this.sqlite.exec("ROLLBACK");
			throw error;
		}
	}
	async exec(sql) {
		const start = performance.now();
		this.sqlite.exec(sql);
		return {
			count: 1,
			duration: performance.now() - start
		};
	}
	close() {
		this.sqlite.close();
	}
};
