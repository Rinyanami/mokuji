function importState(raw, existing) {
	const backup = objectType({
		format: literalType("duji-library"),
		version: literalType(1),
		state: objectType({
			cotexSources: arrayType(sourceRecordSchema).max(9e3).optional(),
			customBooks: arrayType(unknownType()).max(3e3),
			entries: arrayType(unknownType()).max(3e3),
			events: arrayType(unknownType()).max(1e5).optional()
		})
	}).parse(raw);
	const state = structuredClone(existing);
	for (const candidate of backup.state.customBooks) {
		const rawBook = objectType({ id: text(100).regex(/^custom-[a-zA-Z0-9-]+$/) }).passthrough().parse(candidate);
		const value = bookInput.parse(candidate);
		const book = {
			id: rawBook.id,
			...value,
			author: value.author || "作者未填写",
			category: value.category || "文学",
			tags: value.tags || [],
			country: value.country || "",
			language: value.language || "",
			description: value.description || "",
			cover: "",
			color: "#6b867b",
			unit: value.unit || "页",
			total: value.total ?? null,
			publicationStatus: value.publicationStatus || "未记录",
			isCustom: true
		};
		const bgm = /^custom-bgm-([1-9]\d{0,9})$/.exec(book.id);
		if (bgm) {
			book.cover = bangumiCover(Number(bgm[1]));
			book.sourceUrl = bangumiUrl(Number(bgm[1]));
		}
		state.customBooks = state.customBooks.filter((b) => b.id !== book.id).concat(book);
	}
	for (const candidate of backup.state.entries) {
		const parsed = partialEntry.parse(candidate);
		const book = getBook(state, parsed.bookId);
		const next = mergeEntry(parsed, book, state.entries.find((e) => e.bookId === book.id));
		const restoredLink = objectType({ catalogWorkId: text(80).min(1).optional() }).parse(candidate);
		if (restoredLink.catalogWorkId) next.catalogWorkId = restoredLink.catalogWorkId;
		const timestamps = objectType({
			updatedAt: dateText.optional(),
			startedAt: dateText.optional(),
			finishedAt: dateText.optional()
		}).parse(candidate);
		next.updatedAt = timestamps.updatedAt || "";
		next.startedAt = timestamps.startedAt || "";
		next.finishedAt = timestamps.finishedAt || "";
		for (const older of state.events) if (older.bookId === book.id) {
			older.previous = null;
			older.resultUpdatedAt = "";
		}
		state.entries = state.entries.filter((e) => e.bookId !== book.id).concat(next);
	}
	if (backup.state.cotexSources?.length) {
		const sources = state.cotexSources ??= [];
		for (const record of backup.state.cotexSources) {
			getBook(state, record.bookId);
			const index = sources.findIndex((source) => sameSource(source, record));
			if (index < 0) sources.push(record);
			else if (JSON.stringify(sources[index]) !== JSON.stringify(record)) sources[index] = {
				...record,
				version: Math.max(record.version, sources[index].version) + 1
			};
		}
	}
	const knownEvents = new Set(state.events.map((e) => e.id));
	for (const candidate of backup.state.events || []) {
		const e = objectType({
			id: text(100).min(1),
			bookId: text(100),
			at: text(50),
			kind: text(60),
			detail: text(1e3)
		}).parse(candidate);
		if (knownEvents.has(e.id)) continue;
		if (![...catalog, ...state.customBooks].some((b) => b.id === e.bookId)) continue;
		const at = safeImportedDate(e.at);
		if (!at) continue;
		state.events.push({
			...e,
			at,
			previous: null,
			resultUpdatedAt: ""
		});
		knownEvents.add(e.id);
	}
	state.events.sort((a, b) => b.at.localeCompare(a.at));
	return state;
}
function attachBangumi(state, input, now) {
	const id = subjectId.parse(input.bangumiId);
	const targetId = text(100).min(1).optional().parse(input.targetId);
	const importedId = `custom-bgm-${id}`;
	const bookId = targetId || importedId;
	if (state.entries.some((entry) => entry.bangumiId === id && entry.bookId !== bookId)) throw new AppError("这个 Bangumi 条目已关联到书架里的另一部作品。", 409);
	let book = [...catalog, ...state.customBooks].find((item) => item.id === bookId);
	if (!book) {
		if (targetId) throw new AppError("找不到选择的书架作品。", 404);
		const value = bookInput.parse(input.book);
		const category = value.category || "文学";
		book = {
			id: importedId,
			title: value.title,
			originalTitle: value.originalTitle,
			author: value.author || "作者未填写",
			description: value.description || "",
			category,
			unit: bangumiUnit(category),
			tags: value.tags || [],
			country: "",
			language: "",
			total: null,
			publicationStatus: "未记录",
			color: "#6b867b",
			cover: bangumiCover(id),
			isCustom: true,
			sourceUrl: bangumiUrl(id)
		};
		state.customBooks.push(book);
	}
	const previous = state.entries.find((entry) => entry.bookId === bookId);
	if (previous?.bangumiId === id) return false;
	if (previous?.bangumiId || book.id.startsWith("custom-bgm-") && book.id !== importedId) throw new AppError("这部作品已关联其他 Bangumi 条目，请核对版本。", 409);
	const incoming = objectType({
		status: enumType(statuses).optional(),
		rating: score.optional()
	}).parse(input.collection || {});
	const next = {
		...previous || {
			...defaultEntry(book, incoming.status || "想读"),
			rating: incoming.rating ?? null
		},
		bangumiId: id,
		updatedAt: now
	};
	state.entries = state.entries.filter((entry) => entry.bookId !== bookId).concat(next);
	event(state, book, next, previous || null, "关联 Bangumi", previous ? "已关联作品条目" : `加入${next.status}书架`);
	return true;
}
