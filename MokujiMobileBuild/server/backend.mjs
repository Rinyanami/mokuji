async function stableId(parts) {
	const bytes = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(JSON.stringify(parts)));
	return "work-" + Array.from(new Uint8Array(bytes), (b) => b.toString(16).padStart(2, "0")).join("");
}
